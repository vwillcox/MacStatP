# Glyphs whose advance shouldn't just be width + 5.
ADVANCE_OVERRIDE = {
    "I": 13,
    ".": 12,
    ",": 12,
    ":": 12,
    "'": 12,
    "!": 12,
    " ": 12,
}


def advance(ch):
    w, _ = GLYPHS[ch]
    return ADVANCE_OVERRIDE.get(ch, w + 5)


def polys(ch):
    return GLYPHS[ch][1]


def text_width(s, tracking=0):
    return sum(advance(c) + tracking for c in s if c in GLYPHS)
