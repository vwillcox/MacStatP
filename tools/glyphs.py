"""Authoring source for "Presto Techno" — a bold squarish display face.

Every glyph is a list of filled convex polygons on a 20x28 grid: x runs
0..20 (wider for M/W), y runs 0 at the cap line to 28 at the baseline.
Stems are 5 units. Polygons are filled independently, so overlapping
strokes are fine and counters are formed by leaving gaps rather than by
even-odd fill (the device renderer has no hole support).

Run tools/fontpreview.py to rasterise a specimen, tools/build_font.py to
emit the packed device table.
"""

CAP = 28          # baseline sits at y = CAP
STEM = 5
DEFAULT_ADV = 25  # advance for a 20-wide glyph


def R(x0, y0, x1, y1):
    """Axis-aligned bar."""
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]


def Q(*pts):
    """Arbitrary quad/triangle, given in order."""
    return list(pts)


def ring(outer, inner):
    """Closed outline as quads between matching outer/inner points.

    Lets glyphs have real counters without needing even-odd fill.
    """
    n = len(outer)
    return [[outer[i], outer[(i + 1) % n], inner[(i + 1) % n], inner[i]]
            for i in range(n)]


